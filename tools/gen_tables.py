#!/usr/bin/env python3
# Generates the AES S-box and the T-tables used by the T-table implementation.
# Output goes to src/aes_tables.c, so the tables end up in .rodata of the
# shared library (read-only pages are shared between processes, which is
# exactly what Flush+Reload needs).

import sys


def xtime(a):
    a <<= 1
    if a & 0x100:
        a ^= 0x11b
    return a & 0xff


def mul(a, b):
    r = 0
    while b:
        if b & 1:
            r ^= a
        a = xtime(a)
        b >>= 1
    return r


def inverse(a):
    if a == 0:
        return 0
    for b in range(1, 256):
        if mul(a, b) == 1:
            return b
    raise ValueError("no inverse")


def sbox_value(a):
    b = inverse(a)
    r = b
    for i in range(1, 5):
        r ^= ((b << i) | (b >> (8 - i))) & 0xff
    return r ^ 0x63


def word(b0, b1, b2, b3):
    return (b0 << 24) | (b1 << 16) | (b2 << 8) | b3


def table(name, values, out):
    out.write(f"const uint32_t {name}[256] __attribute__((aligned(64))) = {{\n")
    for i in range(0, 256, 4):
        row = ", ".join(f"0x{v:08x}U" for v in values[i:i + 4])
        out.write(f"    {row},\n")
    out.write("};\n\n")


def main():
    sbox = [sbox_value(x) for x in range(256)]

    te0 = [word(mul(s, 2), s, s, mul(s, 3)) for s in sbox]
    te1 = [word(mul(s, 3), mul(s, 2), s, s) for s in sbox]
    te2 = [word(s, mul(s, 3), mul(s, 2), s) for s in sbox]
    te3 = [word(s, s, mul(s, 3), mul(s, 2)) for s in sbox]
    te4 = [word(s, s, s, s) for s in sbox]

    out = sys.stdout
    out.write("// Generated by tools/gen_tables.py, don't edit by hand.\n\n")
    out.write("#include <stdint.h>\n\n")
    # Every table is 1 KB and aligned to 64 bytes, so each one covers
    # exactly 16 cache lines and no line is shared between two tables.
    table("Te0", te0, out)
    table("Te1", te1, out)
    table("Te2", te2, out)
    table("Te3", te3, out)
    table("Te4", te4, out)


if __name__ == "__main__":
    main()
